'use client';

import { Citation } from '@/lib/api';
import { motion, AnimatePresence } from 'framer-motion';
import { Bot, User, ChevronDown, ChevronUp, Sparkles } from 'lucide-react';
import { useState } from 'react';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';
import rehypeHighlight from 'rehype-highlight';
import 'highlight.js/styles/github-dark.css';

interface ChatMessageProps {
  role: 'user' | 'assistant';
  content: string;
  citations?: Citation[];
  model?: string;
}

export default function ChatMessage({ role, content, citations, model }: ChatMessageProps) {
  const isAssistant = role === 'assistant';
  const [showSources, setShowSources] = useState(false);

  return (
    <motion.div
      initial={{ opacity: 0, y: 15 }}
      animate={{ opacity: 1, y: 0 }}
      className={`flex gap-4 p-6 ${isAssistant ? 'bg-[#101014] border-y border-white/5 text-slate-200' : 'bg-[#0A0A0C] text-slate-200'}`}
    >
      <div
        className={`w-10 h-10 rounded-full flex items-center justify-center shrink-0 ${
          isAssistant ? 'bg-indigo-600/20 text-indigo-400 shadow-md ring-1 ring-indigo-500/30' : 'bg-slate-800 text-slate-300 ring-1 ring-white/10'
        }`}
      >
        {isAssistant ? <Bot size={20} /> : <User size={20} />}
      </div>

      <div className="flex-1 space-y-4 pt-1 max-w-4xl overflow-hidden">
        {isAssistant && model && (
          <div className="flex items-center gap-1.5 text-xs font-medium text-indigo-400/80 mb-2">
            <Sparkles size={12} />
            <span>Generated by {model}</span>
          </div>
        )}
        <div className="prose prose-invert prose-indigo max-w-none prose-p:leading-relaxed prose-pre:bg-[#0A0A0C] prose-pre:border prose-pre:border-white/10 prose-headings:font-semibold">
          {isAssistant ? (
            <ReactMarkdown
              remarkPlugins={[remarkGfm]}
              rehypePlugins={[rehypeHighlight]}
            >
              {content}
            </ReactMarkdown>
          ) : (
            <p className="whitespace-pre-wrap">{content}</p>
          )}
        </div>

        {citations && citations.length > 0 && (
          <div className="mt-4">
            <button
              onClick={() => setShowSources(!showSources)}
              className="flex items-center gap-1.5 text-sm font-medium text-slate-400 hover:text-indigo-400 transition-colors bg-[#1A1A24] border border-white/10 rounded-full px-4 py-1.5 shadow-sm"
            >
              {showSources ? <ChevronUp size={16} /> : <ChevronDown size={16} />}
              {citations.length} Sources Used
            </button>

            <AnimatePresence>
              {showSources && (
                <motion.div
                  initial={{ opacity: 0, height: 0 }}
                  animate={{ opacity: 1, height: 'auto' }}
                  exit={{ opacity: 0, height: 0 }}
                  className="overflow-hidden"
                >
                  <div className="grid gap-2 mt-3 pt-3 border-t border-white/10">
                    {citations.map((cit, idx) => (
                      <div
                        key={idx}
                        className="bg-[#15151D] border border-white/5 rounded-lg p-3 text-sm shadow-sm flex flex-col gap-1 border-l-4 border-l-indigo-500"
                      >
                        <div className="font-semibold text-slate-300 flex justify-between">
                          <span>{cit.filename}</span>
                          <span className="text-xs font-mono text-slate-500 bg-black/40 px-2 py-0.5 rounded">
                            Score: {cit.score.toFixed(3)}
                          </span>
                        </div>
                        <div className="text-slate-500 text-xs flex gap-3">
                          <span>Page {cit.page}</span>
                          <span>Chunk ID: {cit.chunk_id.slice(0, 8)}...</span>
                        </div>
                      </div>
                    ))}
                  </div>
                </motion.div>
              )}
            </AnimatePresence>
          </div>
        )}
      </div>
    </motion.div>
  );
}
